def fname(seq):
    s = seq - 1
    h, rem = divmod(s, 3600)
    m, sec = divmod(rem, 60)
    return "frame_{:06d}_{:02d}h{:02d}m{:02d}s000ms.jpg".format(seq, h, m, sec)

def ts(seq):
    s = seq - 1
    return "{:02d}:{:02d}".format(s // 60, s % 60)

